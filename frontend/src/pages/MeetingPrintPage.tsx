import { useEffect, useState } from "react";
import { useParams } from "react-router-dom";

import { meetingsApi } from "../api";
import { formatClock, meetingLanguageName } from "../lib/meetings";
import type { MeetingDetail } from "../types";

/** Print-friendly view; the browser's "Save as PDF" renders Tamil and Devanagari text correctly. */
export function MeetingPrintPage() {
  const { id = "" } = useParams();
  const [m, setM] = useState<MeetingDetail | null>(null);

  useEffect(() => {
    meetingsApi.get(id).then(setM).catch(() => setM(null));
  }, [id]);

  useEffect(() => {
    if (m) setTimeout(() => window.print(), 400);
  }, [m]);

  if (!m) return <p className="p-10 text-sm">Loading…</p>;
  const hasTranslation = m.segments.some((s) => s.translated_text);
  return (
    <article className="mx-auto max-w-4xl bg-surface p-10 text-[13px] leading-relaxed text-ink">
      <h1 className="text-2xl font-semibold">{m.title}</h1>
      <p className="mt-1 text-muted">
        {new Date(m.recorded_at).toLocaleString()} · {formatClock(m.duration_seconds * 1000)} · {meetingLanguageName(m.spoken_language)}
        {m.translation_language && ` → ${meetingLanguageName(m.translation_language)}`}
      </p>
      {m.summary && (
        <section className="mt-6 space-y-3">
          <h2 className="text-lg font-semibold">Summary</h2>
          <p>{m.summary.summary}</p>
          {(
            [
              ["Key discussion points", m.summary.key_points],
              ["Decisions", m.summary.decisions],
              ["Open questions and follow-ups", m.summary.open_questions],
            ] as const
          ).map(([title, items]) => (
            <div key={title}>
              <h3 className="font-semibold">{title}</h3>
              {items.length ? (
                <ul className="list-disc pl-5">
                  {items.map((p, i) => (
                    <li key={i}>{p.text}</li>
                  ))}
                </ul>
              ) : (
                <p className="text-muted">None.</p>
              )}
            </div>
          ))}
          <div>
            <h3 className="font-semibold">Action items</h3>
            {m.action_items.length ? (
              <ul className="list-disc pl-5">
                {m.action_items.map((a) => (
                  <li key={a.id}>
                    {a.done ? "✔ " : ""}
                    {a.text}
                    {(a.owner_name || a.deadline) && ` (${[a.owner_name && `owner: ${a.owner_name}`, a.deadline && `due: ${a.deadline}`].filter(Boolean).join(", ")})`}
                  </li>
                ))}
              </ul>
            ) : (
              <p className="text-muted">None.</p>
            )}
          </div>
        </section>
      )}
      <h2 className="mt-8 text-lg font-semibold">Transcript</h2>
      <table className="mt-2 w-full border-collapse">
        <tbody>
          {m.segments.map((s) => (
            <tr key={s.index} className="border-b border-line align-top">
              <td className="w-20 py-1.5 pr-3 font-mono text-[11px] text-muted">{formatClock(s.start_ms)}</td>
              <td className="py-1.5 pr-3">
                {s.speaker && <b>{s.speaker}: </b>}
                {s.original_text}
              </td>
              {hasTranslation && <td className="py-1.5 text-muted">{s.translated_text}</td>}
            </tr>
          ))}
        </tbody>
      </table>
      <p className="mt-6 text-[11px] text-muted">Generated by AI Call Translator. AI transcripts and summaries can contain mistakes.</p>
    </article>
  );
}
