import { useState } from "react";

import { ApiError, meetingsApi } from "../../api";
import { MEETING_LANGUAGES, formatClock } from "../../lib/meetings";
import type { MeetingActionItem, MeetingConfig, MeetingDetail, NotePoint } from "../../types";

interface Props {
  meeting: MeetingDetail;
  config: MeetingConfig;
  pending: boolean;
  onRequested: () => void;
  onSeek: (ms: number) => void;
  onActionItem: (item: MeetingActionItem) => void;
}

export function MeetingSummary({ meeting, config, pending, onRequested, onSeek, onActionItem }: Props) {
  const [language, setLanguage] = useState(meeting.summary_language);
  const [error, setError] = useState("");
  const startOf = (index: number) => meeting.segments.find((s) => s.index === index)?.start_ms ?? 0;

  async function generate() {
    setError("");
    try {
      await meetingsApi.summarize(meeting.id, language);
      onRequested();
    } catch (err) {
      setError(err instanceof ApiError ? err.message : "Could not start the summary");
    }
  }

  const notes = meeting.summary;
  const canGenerate = config.summaries_enabled && meeting.segments.length > 0;

  return (
    <section className="card space-y-5 p-5" aria-label="Meeting notes">
      <div className="flex flex-wrap items-center gap-3">
        <h2 className="font-semibold">AI meeting notes</h2>
        <div className="flex-1" />
        <select className="field w-36 py-1.5" value={language} onChange={(e) => setLanguage(e.target.value as typeof language)} aria-label="Notes language">
          {MEETING_LANGUAGES.map((l) => (
            <option key={l.code} value={l.code}>
              {l.name}
            </option>
          ))}
        </select>
        <button className="btn-primary py-1.5" disabled={!canGenerate || pending} onClick={() => void generate()}>
          {pending ? "Writing notes…" : notes ? "Regenerate" : "Generate notes"}
        </button>
      </div>
      {!config.summaries_enabled && (
        <p className="rounded-xl bg-subtle px-4 py-3 text-sm text-muted">
          AI notes are not configured on this server (set ANTHROPIC_API_KEY). Transcripts, translations and exports still work.
        </p>
      )}
      {error && <p className="text-sm text-danger">{error}</p>}
      {meeting.summary_error && !pending && <p className="text-sm text-danger">Last attempt failed: {meeting.summary_error}</p>}
      {notes ? (
        <>
          <p className="leading-relaxed">{notes.summary}</p>
          <NoteList title="Key discussion points" items={notes.key_points} onCite={(i) => onSeek(startOf(i))} />
          <NoteList title="Decisions" items={notes.decisions} onCite={(i) => onSeek(startOf(i))} empty="No explicit decisions were recorded." />
          <div>
            <h3 className="mb-2 text-sm font-semibold uppercase tracking-wide text-muted">Action items</h3>
            {meeting.action_items.length === 0 && <p className="text-sm text-muted">No action items were stated.</p>}
            <ul className="space-y-2">
              {meeting.action_items.map((item) => (
                <ActionRow key={item.id} meetingId={meeting.id} item={item} onChange={onActionItem} onCite={(i) => onSeek(startOf(i))} />
              ))}
            </ul>
          </div>
          <NoteList title="Open questions and follow-ups" items={notes.open_questions} onCite={(i) => onSeek(startOf(i))} empty="None." />
          <p className="text-xs text-muted">
            Generated by {meeting.summary_model} on {meeting.summary_generated_at ? new Date(meeting.summary_generated_at).toLocaleString() : "—"}.
            Every item links to the transcript; owners and deadlines appear only when stated in the meeting. AI notes can be wrong.
          </p>
        </>
      ) : (
        canGenerate && !pending && <p className="text-sm text-muted">Generate a summary, decisions, action items and open questions from the transcript.</p>
      )}
    </section>
  );
}

function Cites({ refs, onCite }: { refs: number[]; onCite: (index: number) => void }) {
  return (
    <span className="ml-1 inline-flex flex-wrap gap-1 align-middle">
      {refs.map((r) => (
        <button key={r} className="rounded bg-subtle px-1.5 text-[11px] text-brand hover:bg-brand-soft" onClick={() => onCite(r)} title="Play this part">
          #{r + 1}
        </button>
      ))}
    </span>
  );
}

function NoteList({ title, items, onCite, empty }: { title: string; items: NotePoint[]; onCite: (i: number) => void; empty?: string }) {
  return (
    <div>
      <h3 className="mb-2 text-sm font-semibold uppercase tracking-wide text-muted">{title}</h3>
      {items.length === 0 ? (
        <p className="text-sm text-muted">{empty ?? "None."}</p>
      ) : (
        <ul className="list-disc space-y-1.5 pl-5 text-sm">
          {items.map((p, i) => (
            <li key={i}>
              {p.text}
              <Cites refs={p.segments} onCite={onCite} />
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}

function ActionRow({ meetingId, item, onChange, onCite }: { meetingId: string; item: MeetingActionItem; onChange: (i: MeetingActionItem) => void; onCite: (i: number) => void }) {
  async function toggle() {
    try {
      onChange(await meetingsApi.updateActionItem(meetingId, item.id, { done: !item.done }));
    } catch {
      /* keep current state */
    }
  }
  return (
    <li className="flex items-start gap-3 rounded-xl border border-line px-3 py-2 text-sm">
      <input type="checkbox" className="mt-1" checked={item.done} onChange={() => void toggle()} aria-label="Done" />
      <div className={item.done ? "text-muted line-through" : ""}>
        {item.text}
        <Cites refs={item.segment_indexes} onCite={onCite} />
        <div className="mt-0.5 text-xs text-muted">
          {item.owner_name ? `Owner: ${item.owner_name}` : "Owner: not stated"} · {item.deadline ? `Due: ${item.deadline}` : "No deadline stated"}
        </div>
      </div>
    </li>
  );
}

export function durationLabel(seconds: number) {
  return formatClock(seconds * 1000);
}
