"""TXT and DOCX exports. (PDF: the web app's print view — browsers shape Tamil/Devanagari text correctly.)"""

from __future__ import annotations

import io

from django.utils import timezone

from .languages import MEETING_LANGUAGES
from .models import Meeting


def ts(ms: int) -> str:
    s = ms // 1000
    h, rem = divmod(s, 3600)
    m, sec = divmod(rem, 60)
    return f"{h:d}:{m:02d}:{sec:02d}" if h else f"{m:02d}:{sec:02d}"


def _lang(code: str) -> str:
    return MEETING_LANGUAGES.get(code, code or "—")


def _notes(meeting: Meeting) -> list[tuple[str, list[str]]]:
    notes = meeting.summary or {}
    sections = []
    for key, title in (("key_points", "Key discussion points"), ("decisions", "Decisions"), ("open_questions", "Open questions and follow-ups")):
        items = [p["text"] for p in notes.get(key, [])]
        sections.append((title, items))
    actions = []
    for a in meeting.action_items.all():
        extra = ", ".join(x for x in (f"owner: {a.owner_name}" if a.owner_name else "", f"deadline: {a.deadline}" if a.deadline else "") if x)
        actions.append(f"{'[x]' if a.done else '[ ]'} {a.text}" + (f" ({extra})" if extra else ""))
    sections.insert(2, ("Action items", actions))
    return sections


def export_txt(meeting: Meeting) -> str:
    when = timezone.localtime(meeting.recorded_at).strftime("%d %b %Y, %H:%M")
    lines = [meeting.title, "=" * len(meeting.title), f"Date: {when}", f"Duration: {ts(int(meeting.duration_seconds * 1000))}"]
    lines.append(f"Language: {_lang(meeting.spoken_language)}" + (f" · Translation: {_lang(meeting.translation_language)}" if meeting.translation_language else ""))
    if meeting.summary:
        lines += ["", "SUMMARY", meeting.summary.get("summary", "")]
        for title, items in _notes(meeting):
            lines += ["", title.upper()] + ([f"- {i}" for i in items] if items else ["(none)"])
    lines += ["", "TRANSCRIPT"]
    for seg in meeting.segments.all():
        who = f" {seg.speaker}:" if seg.speaker else ""
        lines.append(f"[{ts(seg.start_ms)} - {ts(seg.end_ms)}]{who} {seg.original_text}")
        if seg.translated_text and seg.translated_text != seg.original_text:
            lines.append(f"    ({_lang(seg.translation_language)}) {seg.translated_text}")
    lines += ["", "Generated by AI Call Translator. AI transcripts and summaries can contain mistakes."]
    return "\n".join(lines) + "\n"


def export_docx(meeting: Meeting) -> bytes:
    from docx import Document
    from docx.shared import Pt

    doc = Document()
    doc.add_heading(meeting.title, level=0)
    when = timezone.localtime(meeting.recorded_at).strftime("%d %b %Y, %H:%M")
    doc.add_paragraph(f"{when} · {ts(int(meeting.duration_seconds * 1000))} · {_lang(meeting.spoken_language)}")
    if meeting.summary:
        doc.add_heading("Summary", level=1)
        doc.add_paragraph(meeting.summary.get("summary", ""))
        for title, items in _notes(meeting):
            doc.add_heading(title, level=2)
            if not items:
                doc.add_paragraph("(none)")
            for item in items:
                doc.add_paragraph(item, style="List Bullet")
    doc.add_heading("Transcript", level=1)
    has_translation = any(s.translated_text for s in meeting.segments.all())
    table = doc.add_table(rows=1, cols=3 if has_translation else 2)
    table.style = "Table Grid"
    header = table.rows[0].cells
    header[0].text, header[1].text = "Time", "Original"
    if has_translation:
        header[2].text = f"Translation ({_lang(meeting.translation_language)})"
    for seg in meeting.segments.all():
        cells = table.add_row().cells
        cells[0].text = f"{ts(seg.start_ms)}–{ts(seg.end_ms)}"
        cells[1].text = (f"{seg.speaker}: " if seg.speaker else "") + seg.original_text
        if has_translation:
            cells[2].text = seg.translated_text
    for row in table.rows:
        for cell in row.cells:
            for p in cell.paragraphs:
                for run in p.runs:
                    run.font.size = Pt(10)
    doc.add_paragraph("Generated by AI Call Translator. AI transcripts and summaries can contain mistakes.")
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def export_csv(meeting: Meeting) -> str:
    """One row per transcript segment. A UTF-8 BOM so Excel shows Tamil/Devanagari correctly."""
    import csv

    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["index", "start", "end", "start_ms", "end_ms", "speaker", "language", "original", "translation_language", "translation"])
    for seg in meeting.segments.all():
        w.writerow([seg.index, ts(seg.start_ms), ts(seg.end_ms), seg.start_ms, seg.end_ms, seg.speaker, seg.language, seg.original_text, seg.translation_language, seg.translated_text])
    return "﻿" + buf.getvalue()


def export_json(meeting: Meeting) -> dict:
    return {
        "id": str(meeting.id),
        "title": meeting.title,
        "source": meeting.source,
        "status": meeting.status,
        "recorded_at": meeting.recorded_at.isoformat(),
        "duration_seconds": meeting.duration_seconds,
        "spoken_language": meeting.spoken_language,
        "translation_language": meeting.translation_language,
        "transcription_engine": meeting.transcription_engine,
        "segments": [
            {
                "index": s.index,
                "start_ms": s.start_ms,
                "end_ms": s.end_ms,
                "speaker": s.speaker or None,
                "language": s.language or None,
                "original_text": s.original_text,
                "translated_text": s.translated_text or None,
                "translation_language": s.translation_language or None,
            }
            for s in meeting.segments.all()
        ],
        # The notes keep their transcript evidence (segment indexes) so readers can tell found facts from inference.
        "summary": meeting.summary,
        "summary_model": meeting.summary_model or None,
        "action_items": [
            {"text": a.text, "owner": a.owner_name or None, "deadline": a.deadline or None, "segment_indexes": a.segment_indexes, "done": a.done}
            for a in meeting.action_items.all()
        ],
        "disclaimer": "AI transcripts and summaries can contain mistakes.",
    }


def _subtitle_time(ms: int, sep: str) -> str:
    h, rem = divmod(ms, 3_600_000)
    m, rem = divmod(rem, 60_000)
    s, milli = divmod(rem, 1000)
    return f"{h:02d}:{m:02d}:{s:02d}{sep}{milli:03d}"


def _subtitle_text(seg, translated: bool) -> str:
    text = (seg.translated_text if translated else "") or seg.original_text
    return (f"{seg.speaker}: " if seg.speaker else "") + text


def export_subtitles(meeting: Meeting, fmt: str, translated: bool = False) -> str:
    """SRT or WebVTT from the segment timestamps; segments with no duration are skipped (no invented times)."""
    sep = "," if fmt == "srt" else "."
    blocks = [] if fmt == "srt" else ["WEBVTT", ""]
    n = 0
    for seg in meeting.segments.all():
        if seg.end_ms <= seg.start_ms:
            continue
        n += 1
        if fmt == "srt":
            blocks.append(str(n))
        blocks += [f"{_subtitle_time(seg.start_ms, sep)} --> {_subtitle_time(seg.end_ms, sep)}", _subtitle_text(seg, translated), ""]
    return "\n".join(blocks)
